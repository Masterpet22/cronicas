import assert from "node:assert/strict";
import { createCharacter, createDefaultSave, normalizeSave, spendAttribute, chooseDoctorMissionRoute, startDoctorMission, deliverBestiaryBook, awardEncounter, completeMission } from "../src/save.js";
import { SAGA_TUTORIAL, TUTORIAL_LESSON_IDS } from "../src/content/sagas/futuro-prometedor/tutorial.js";
import { COMBAT_LESSONS } from "../src/content/sagas/futuro-prometedor/combat-lessons.js";
import { currentTutorialCourse, lessonCompleted, normalizeSagaTutorial, observeTutorialChanges, observeTutorialEvent, pendingTutorialPreparation, recordTutorialLesson, tutorialCourseFor } from "../src/tutorial-system.js";
import { investResonance, resonancePoints } from "../src/skills/progression.js";
import { equipTaijutsu } from "../src/skills/taijutsu.js";
import { purchaseItem, sellItem } from "../src/inventory.js";
import { MISSIONS } from "../src/content/index.js";
import { recordBattleLesson } from "../src/battle/tutorial-progress.js";
const fresh = () => createCharacter(createDefaultSave(), { name: "Alumno", affinity: "fuego" });
assert.equal(new Set(TUTORIAL_LESSON_IDS).size, TUTORIAL_LESSON_IDS.length);
assert.equal(SAGA_TUTORIAL.length, 7);
const firstMission = MISSIONS.find(m => tutorialCourseFor(m)?.battle === "basics");
for (const affinity of ["fuego", "agua", "tierra", "viento"]) {
  let pupil = createCharacter(createDefaultSave(), { name: "Novicio", affinity });
  firstMission.encounters.forEach((id, encounterIndex) => { pupil = awardEncounter(pupil, id, { firstClear: true, mission: firstMission, encounterIndex, encounterIds: firstMission.encounters }).save; });
  pupil = completeMission(pupil, firstMission.id).save;
  assert.ok(pupil.progression.attributePoints >= 1 && resonancePoints(pupil) >= 2 && pupil.progression.coins >= 36, "La primera victoria financia la preparación completa");
  pupil = investResonance(investResonance(pupil, "physical_0"), "physical_1");
  assert.ok(equipTaijutsu(pupil, 0, "physical_1").taijutsuLoadout.includes("physical_1"));
}
for (const course of SAGA_TUTORIAL) {
  assert.ok(MISSIONS.some(mission => mission.id === course.missionId));
  assert.ok(course.practices.length);
  if (course.battle) for (const step of COMBAT_LESSONS[course.battle].actions) if (step.lesson) assert.ok(course.practices.includes(step.lesson));
}
let save = fresh();
assert.equal(currentTutorialCourse(save).missionId, "m01");
assert.equal(pendingTutorialPreparation(save).id, "command");
save = observeTutorialEvent(save, { type: "saga" });
assert.ok(lessonCompleted(observeTutorialChanges(save, fresh(), "dojo"), "command"), "Una instantánea vieja no borra lecciones posteriores");
assert.equal(pendingTutorialPreparation(save).id, "equipment");
save = recordTutorialLesson(save, "invented");
assert.equal(lessonCompleted(save, "invented"), false);
const legacy = structuredClone(save); delete legacy.campaign.sagaTutorial;
legacy.campaign.completedMissions = ["m01"];
const migrated = normalizeSave(legacy);
for (const id of SAGA_TUTORIAL[0].practices) assert.ok(lessonCompleted(migrated, id));
assert.equal(lessonCompleted(migrated, "investigation"), false);
assert.deepEqual(normalizeSagaTutorial({ completed: ["strike", "strike", "invalid"] }).completed, ["strike"]);
save = fresh(); save.campaign.completedMissions = ["m01"];
save.progression.level = 2; save.progression.attributePoints = 2; save.progression.coins = 100;
save = observeTutorialChanges(save, spendAttribute(save, "health"), "dojo");
assert.equal(pendingTutorialPreparation(save).id, "foundation");
save = observeTutorialChanges(save, investResonance(save, "physical_0"), "dojo");
assert.equal(pendingTutorialPreparation(save).id, "learn-punch");
save = observeTutorialChanges(save, investResonance(save, "physical_1"), "dojo");
save = observeTutorialChanges(save, equipTaijutsu(save, 0, "physical_1"), "dojo");
const original = [...save.loadout];
save = observeTutorialChanges(save, { ...save, loadout: original.slice(1) }, "dojo");
assert.equal(pendingTutorialPreparation(save).id, "equip-technique");
save = observeTutorialChanges(save, { ...save, loadout: original }, "dojo");
save = observeTutorialChanges(save, purchaseItem(save, "health_potion", 1).save, "shop");
assert.equal(lessonCompleted(save, "buy-potions"), false);
save = observeTutorialChanges(save, purchaseItem(save, "health_potion", 2).save, "shop");
assert.equal(lessonCompleted(save, "buy-potions"), true);
save = observeTutorialChanges(save, sellItem(save, "health_potion", 1).save, "shop");
assert.equal(pendingTutorialPreparation(save), null);
save.campaign.completedMissions.push("s01"); save.inventory.items.health_potion = 0;
assert.equal(pendingTutorialPreparation(save).id, "potion-ready");
save = recordTutorialLesson(save, "potion");
assert.equal(pendingTutorialPreparation(save), null, "Reanudar después de consumir no exige otra poción");
save.campaign.completedMissions.push("m02", "s02"); save.campaign.archiveUnlocked = true;
save = observeTutorialEvent(save, { type: "affinity-answer", key: "agua" });
assert.equal(lessonCompleted(save, "affinity-cycle"), false);
save = observeTutorialEvent(save, { type: "affinity-answer", key: "viento" });
assert.equal(lessonCompleted(save, "affinity-cycle"), true);
const routeMission = MISSIONS.find(mission => mission.type === "route-search");
const routeSave = fresh(); routeSave.campaign.completedMissions = ["m01", "s01", "m02"];
let route = startDoctorMission(routeSave, routeMission);
route = chooseDoctorMissionRoute(route, "elevated");
assert.equal(lessonCompleted(route, "route-1"), true);
// Las rutas inválidas nunca acreditan una práctica.
assert.equal(lessonCompleted(chooseDoctorMissionRoute(route, "invalid"), "route-2"), false);
save.campaign.doctorBookDeliveryPending = true;
assert.equal(lessonCompleted(deliverBestiaryBook(save), "book"), true);
const mission = MISSIONS.find(m => tutorialCourseFor(m)?.battle === "basics");
const scene = { mission, saveData: fresh(), missionStartSave: fresh(), rewardPreviewSave: fresh() };
scene.rewardPreviewSave.progression.coins = 999;
recordBattleLesson(scene, "boss-phase");
assert.equal(lessonCompleted(scene.saveData, "boss-phase"), false, "Varek no acredita la fase de Raizen");
recordBattleLesson(scene, "strike");
assert.equal(lessonCompleted(scene.missionStartSave, "strike"), true);
assert.equal(scene.missionStartSave.progression.coins, 0);
scene.mission.tutorialReplay = true;
recordBattleLesson(scene, "guard");
assert.equal(lessonCompleted(scene.saveData, "guard"), false);
delete scene.mission.tutorialReplay;
console.log("Saga tutorial: currículo, acciones reales, compras, migración, reanudación y aislamiento de recompensas verificados.");
