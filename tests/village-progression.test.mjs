import assert from "node:assert/strict";
import { createCharacter, createDefaultSave, normalizeSave, completeMission } from "../src/save.js";
import { MISSIONS, STORY_SAGAS } from "../src/content/index.js";
import { locationAccess, reachedSaga } from "../src/village-progression.js";
import { playerRank, playerRankLabel } from "../src/player-rank.js";
import { GAME_DICTIONARY, GAME_TERMS, searchGameDictionary } from "../src/content/game-dictionary.js";
import { VILLAGE_LOCATIONS, createVillageView } from "../src/ui/meta/views/village.js";
import { villageMapHotspots } from "../src/ui/meta/village-map.js";
import { createArchiveView } from "../src/ui/meta/views/archive.js";

const save = createCharacter(createDefaultSave(), { name: "Novicio", affinity: "agua" });
const original = structuredClone(save);
for (const id of ["headquarters", "dojo"]) assert.equal(locationAccess(id, save).unlocked, true);
for (const id of ["shop", "archive", "inn", "missions", "event", "tower", "arena"]) assert.equal(locationAccess(id, save).unlocked, false, id);
save.campaign.sayoEncounterSeen = true;
assert.equal(locationAccess("shop", save).unlocked, false, "Ver el diálogo sin victoria no abre la tienda");
save.campaign.completedMissions = [MISSIONS[0].id];
assert.equal(locationAccess("shop", normalizeSave(save)).unlocked, true);
save.campaign.secondaryBoardUnlocked = true;
assert.equal(normalizeSave(save).campaign.secondaryBoardUnlocked, false, "La antigua bandera del tablón no evita el requisito de saga");
save.campaign.doctorBookDeliveryPending = true;
assert.equal(locationAccess("archive", normalizeSave(save)).unlocked, true, "La entrega obligatoria puede entrar antes del bestiario");
save.campaign.doctorBookDeliveryPending = false;
save.campaign.archiveUnlocked = true;
assert.equal(locationAccess("archive", normalizeSave(save)).unlocked, true);
save.campaign.completedMissions = STORY_SAGAS[0].missionIds.slice(0, -1);
assert.equal(reachedSaga(save), 1);
assert.equal(locationAccess("event", save).unlocked, false);
const final = completeMission(save, MISSIONS.at(-1).id).save;
assert.equal(reachedSaga(final), 2);
assert.equal(final.campaign.secondaryBoardUnlocked, true);
for (const id of ["headquarters", "shop", "archive", "inn", "missions", "event"]) assert.equal(locationAccess(id, normalizeSave(final)).unlocked, true, id);
assert.equal(locationAccess("arena", final).unlocked, false);
const futureSagas = [...STORY_SAGAS, { number: 2, missionIds: ["future-mission"] }];
final.progression.level = 16;
assert.equal(locationAccess("arena", final, futureSagas).unlocked, false, "El nivel no evita la saga 3");
final.campaign.completedMissions.push("future-mission");
assert.equal(reachedSaga(final, futureSagas), 3);
final.progression.level = 15;
assert.equal(locationAccess("arena", final, futureSagas).unlocked, false, "Superior a 15 excluye el nivel 15");
final.progression.level = 16;
assert.equal(locationAccess("arena", final, futureSagas).unlocked, true);

const veteran = structuredClone(original);
veteran.progression.level = 60;
veteran.campaign.elementRank = 3;
veteran.campaign.rank = "Guardián";
assert.equal(playerRank(veteran), 1, "El rango necesita pruebas, no basta el nivel ni un valor guardado");
assert.equal(playerRankLabel(veteran), "Novicio");
assert.equal(locationAccess("tower", veteran).unlocked, false);
veteran.campaign.completedSecondaryMissions = ["affinity_trial_2"];
assert.equal(playerRank(veteran), 2);
assert.equal(normalizeSave(veteran).campaign.rank, "Experto");
assert.equal(locationAccess("tower", normalizeSave(veteran)).unlocked, true, "No exige haber elegido aún la segunda afinidad");
veteran.progression.level = 14;
assert.equal(locationAccess("tower", veteran).unlocked, false);
veteran.progression.level = 30;
veteran.campaign.completedSecondaryMissions.push("affinity_trial_3");
assert.equal(playerRank(veteran), 3);
assert.equal(normalizeSave(veteran).campaign.rank, "Veterano");
assert.equal(locationAccess("tower", veteran).unlocked, true);

assert.equal(new Set(GAME_DICTIONARY.map(entry => entry.id)).size, GAME_DICTIONARY.length);
for (const location of VILLAGE_LOCATIONS) assert.equal(GAME_TERMS[location.id], location.name);
assert.ok(searchGameDictionary("jutsu").some(entry => entry.id === "technique"));
assert.ok(searchGameDictionary("RANGO ELEMENTAL").some(entry => entry.id === "player-rank"));
assert.ok(searchGameDictionary("tablon").some(entry => entry.id === "missions"));
assert.equal(searchGameDictionary("zzzzzzz").length, 0);
const archive = createArchiveView({ escapeHtml: String });
const library = archive.render({ save: { ...original, campaign: { ...original.campaign, doctorBookDeliveryPending: true } } });
assert.match(library, /data-dictionary-search/);
assert.match(library, /data-deliver-book/);
assert.match(library, /Rango del jugador/);
const map = villageMapHotspots(VILLAGE_LOCATIONS.map(location => ({ ...location, ...locationAccess(location.id, original) })), "map.webp", String);
assert.match(map, /class="village-hotspot hotspot-arena is-locked"[^>]*aria-disabled="true"/);
const village = createVillageView({ escapeHtml: String, secondaryMissions: [{ id: "early-contract" }], nextAvailableMission: () => null });
const plaza = village.render({ save: original, view: "plaza" });
assert.doesNotMatch(plaza, /early-contract/, "El mapa no ofrece atajos a encargos con el Tablón bloqueado");
assert.equal(original.campaign.completedMissions.length, 0, "Las consultas y vistas no alteran otra partida");
console.log("Progresión de lugares, tres rangos, límites de nivel y diccionario verificados.");
