import assert from "node:assert/strict";
import { createTraining, trainingActions, trainingDummyProfile } from "../src/training.js";
import { createDefaultSave, createCharacter } from "../src/save.js";
import { ENEMY_ROSTER } from "../src/data.js";
import { createEnemyState } from "../src/battle/enemy-state.js";
import { affinityCycleModifier, validateAffinityOrder } from "../src/affinity-system.js";

const save = createCharacter(createDefaultSave(), { name: "Akio", affinity: "fuego", bodyType: "male" });
save.loadout = [];
save.progression.level = 20;
save.character.affinityXp.fuego = 10000;
save.progression.resonance.investments = { physical_0: 1, physical_1: 1, physical_2: 1, fire_embers: 2 };
save.taijutsuLoadout = [null, null];
const baseline = JSON.stringify(save);
const actions = trainingActions(save);
assert(actions.some(action => action.id === "fire_embers"));
assert(actions.some(action => action.id === "physical_1"));
assert(actions.some(action => action.id === "physical_2"));
assert(!actions.some(action => action.element === "agua"));
assert.equal(actions[0].id, "strike");
assert.equal(actions.at(-1).id, "guard");
assert.equal(new Set(actions.map(action => action.id)).size, actions.length);
assert.equal(JSON.stringify(save), baseline, "Practice must not change equipment or progress");
assert.equal(createTraining().trainingOrigin, "dojo");
assert.equal(createTraining().exhibition, true);
const originalProfile = { ...ENEMY_ROSTER.boss_varek, affinities: ["fuego", "agua"], completedAffinityTrials: ["affinity_trial_2"] };
const originalSnapshot = structuredClone(originalProfile);
const dummyProfile = trainingDummyProfile(originalProfile);
const dummy = createEnemyState(dummyProfile, createTraining());
assert.deepEqual(dummy.affinities, ["normal"]);
assert.equal(dummy.primaryAffinity, "normal");
assert.equal(dummy.maxHp, 10000);
assert.equal(dummy.maxChakra, 0);
assert.equal(dummy.strength, 0);
assert.equal(dummy.speed, 1);
assert.equal(dummy.luck, 0);
assert.equal(dummy.boss, false);
assert.deepEqual(dummyProfile.pattern, []);
assert.deepEqual(dummyProfile.phase2Pattern, []);
assert.deepEqual(originalProfile, originalSnapshot, "El blanco no altera el perfil del que toma su apariencia");
assert.equal(affinityCycleModifier(save.character.affinity, dummy.primaryAffinity), 0);
assert.equal(validateAffinityOrder(["normal"]), false, "Normal no es una configuración elemental del jugador");
assert.equal(createCharacter(createDefaultSave(), { affinity: "normal" }).character.affinity, "fuego");
save.progression.level = 1;
save.character.affinityXp.fuego = 0;
save.progression.resonance.investments = {};
assert(!trainingActions(save).some(action => action.id === "physical_1"));
assert(trainingActions(save).some(action => action.id === "fire_breath"), "Las dos técnicas iniciales son gratuitas");
console.log("Catálogo y aislamiento del entrenamiento verificados.");
