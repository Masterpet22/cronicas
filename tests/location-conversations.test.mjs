import assert from "node:assert/strict";
import { createCharacter, createDefaultSave, normalizeSave } from "../src/save.js";
import { normalizeIntroductions, hasIntroduction, rememberIntroduction, retainIntroductions, NPC_IDLE_LINES, locationChangeComment } from "../src/location-conversations.js";
import { NPCS } from "../src/npcs.js";
import { ITEMS } from "../src/items.js";
import { purchaseItem, sellItem } from "../src/inventory.js";

const original = createCharacter(createDefaultSave(), { name: "Akio", affinity: "fuego", bodyType: "male" });
assert.deepEqual(original.campaign.npcIntroductions, []);
const introduced = normalizeSave(rememberIntroduction(original, "dojo", ["mei"]));
assert.ok(hasIntroduction(introduced, "dojo", ["mei"]));
assert.ok(!hasIntroduction(introduced, "dojo", ["daichi"]), "Un maestro nuevo tiene su propia presentación");
assert.ok(!hasIntroduction(original, "dojo", ["mei"]), "No modifica la partida original ni otra partida");
assert.deepEqual(normalizeIntroductions(["dojo:mei", "dojo:mei", "unknown:mei", null]), ["dojo:mei"]);
assert.deepEqual(normalizeIntroductions("dojo:mei"), []);
assert.deepEqual(normalizeSave(retainIntroductions(original, introduced)).campaign.npcIntroductions, ["dojo:mei"], "Guardar desde una vista abierta antes del diálogo conserva la presentación");
const legacy = structuredClone(original); delete legacy.campaign.npcIntroductions; legacy.version = 25;
assert.deepEqual(normalizeSave(legacy).campaign.npcIntroductions, []);
for (const id of Object.keys(NPCS)) assert.ok(NPC_IDLE_LINES[id]?.length >= 2, `${id} tiene frases propias de espera`);
assert.equal(locationChangeComment("dojo", original, introduced, "mei", ITEMS), null, "Presentarse no inventa una acción del jugador");
const funded = structuredClone(original); funded.progression.coins = 1000;
const bought = purchaseItem(funded, "health_potion", 2);
assert.ok(bought.ok);
assert.match(locationChangeComment("shop", funded, bought.save, "hana", ITEMS), /Buena compra.*×2/);
const sold = sellItem(bought.save, "health_potion", 1);
assert.ok(sold.ok);
assert.match(locationChangeComment("shop", bought.save, sold.save, "hana", ITEMS), /venta/);
assert.equal(locationChangeComment("shop", funded, funded, "hana", ITEMS), null);
const equipped = structuredClone(original); equipped.equipment.weapon = null;
assert.notEqual(locationChangeComment("dojo", original, equipped, "mei"), locationChangeComment("dojo", original, equipped, "daichi"), "La reacción respeta la personalidad del maestro");
console.log("Presentaciones persistentes y reacciones de los encargados verificadas.");
