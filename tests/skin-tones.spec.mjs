import { test, expect } from "@playwright/test";
import { bootPerformanceReference } from "./helpers/performance-harness.mjs";

test("el tono se elige al crear, se cambia gratis en el Dojo y persiste al recargar", async ({ page }, testInfo) => {
  await page.goto("/");
  await page.locator('[data-select-slot="1"]').click();
  await expect(page.locator('[name="skinTone"]')).toHaveCount(2);
  await expect(page.locator('[name="skinTone"][value="claro"]')).toBeChecked();
  await page.locator('.skin-tone-option:has([value="moreno"])').click();
  await page.locator('select[name="bodyType"]').selectOption("female");
  await page.locator('select[name="hair"]').selectOption("4");
  await page.locator('.creator-affinity-choice:has([value="agua"])').click();
  await expect(page.locator('[data-creator-preview] .raster-character-stage')).toHaveAttribute("data-skin-tone", "moreno");
  const filters = await page.locator('.creator-preview .puppet-preview-layer').evaluateAll(layers => layers.map(layer => ({ hair: layer.classList.contains("puppet-preview-hair"), filter: getComputedStyle(layer).filter })));
  expect(filters.filter(layer => !layer.hair).every(layer => layer.filter.includes("skin-tone-moreno"))).toBe(true);
  expect(filters.find(layer => layer.hair).filter).toBe("none");
  await page.locator('.creator-preview img').evaluateAll(images => Promise.all(images.map(image => image.decode())));
  await page.screenshot({ path: testInfo.outputPath("creacion-moreno.png") });
  await page.locator('button[type="submit"]').click();
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem("cronicas-del-sello-save-slot-1")));
  expect((await read()).character.skinTone).toBe("moreno");
  const dialogue = page.locator(".dialogue-overlay");
  for (let i = 0; i < 6 && await dialogue.isVisible(); i++) await dialogue.locator("button").click();
  await page.locator(".debug-tools-trigger").click();
  await page.locator('[data-debug-view="dojo"]').click();
  await page.locator('[data-dojo-tab="appearance"]').click();
  const panel = page.locator("#dojo-panel-appearance");
  await expect(panel.locator('[value="moreno"]')).toBeChecked();
  const before = await read();
  await panel.locator('.skin-tone-option:has([value="claro"])').click();
  await expect(panel.locator('.raster-character-stage')).toHaveAttribute("data-skin-tone", "claro");
  const after = await read();
  expect(after.character.skinTone).toBe("claro");
  expect(after.progression.coins).toBe(before.progression.coins);
  expect(after.inventory).toEqual(before.inventory);
  await page.reload();
  expect((await read()).character.skinTone).toBe("claro");
});

for (const renderer of ["Canvas", "WebGL"]) test(`${renderer}: cuerpo y retratos conservan el tono sin cambiar al rival`, async ({ page }, testInfo) => {
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await bootPerformanceReference(page, { renderer, skinTone: "moreno", bodyType: "female" });
  const result = await page.evaluate(async () => {
    const scene = window.__performanceReference.scene;
    const api = await import("/src/fighters.js?v=0.118.0");
    const appearance = scene.playerAppearance();
    const headKey = api.fighterPuppetTextureKey(appearance, "cabeza");
    const enemyKey = api.fighterPuppetTextureKey(scene.enemyAppearance(), "cabeza");
    const texture = scene.textures.get(headKey);
    const source = texture.getSourceImage();
    const pixels = source.getContext("2d").getImageData(0, 0, source.width, source.height).data;
    let skinPixels = 0;
    for (let i = 0; i < pixels.length; i += 4) if (pixels[i+3] > 200 && pixels[i] > pixels[i+1] + 10 && pixels[i+1] > pixels[i+2]) skinPixels++;
    const before = source.toDataURL();
    api.preparePlayerFighterTextures(scene, appearance);
    const portraitsFit = [scene.playerPortrait, scene.enemyPortrait].every(portrait => [portrait.head, portrait.hair].filter(Boolean).every(layer => [-1, 1].every(sx => [-1, 1].every(sy => Math.hypot(layer.x - portrait.wash.x + sx * layer.displayWidth / 2, layer.y - portrait.wash.y + sy * layer.displayHeight / 2) <= 28.001))));
    scene.busy = false; scene.turnReady = true; scene.refreshHud();
    return { headKey, enemyKey, tone: texture.skinTone, enemyTone: scene.textures.get(enemyKey).skinTone, portrait: scene.playerPortrait.head.texture.key, portraitsFit, skinPixels, stable: before === source.toDataURL(), hairTone: scene.playerPortrait.hair?.texture.skinTone ?? null };
  });
  expect(result.tone).toBe("moreno");
  expect(result.enemyTone).toBe("claro");
  expect(result.headKey).not.toBe(result.enemyKey);
  expect(result.portrait).toBe(result.headKey);
  expect(result.portraitsFit).toBe(true);
  expect(result.skinPixels).toBeGreaterThan(100);
  expect(result.stable).toBe(true);
  expect(result.hairTone).toBeNull();
  await page.screenshot({ path: testInfo.outputPath("combate-dos-tonos.png") });
  const objects = page.getByRole("button", { name: "Abrir objetos de misión" });
  await expect(objects).toHaveText("Objetos");
  await objects.click();
  await expect(page.getByRole("dialog", { name: "Objetos de misión" })).toBeVisible();
  await page.getByRole("button", { name: "Cerrar objetos" }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator(".combat-access.compact")).toBeVisible();
  const fits = await page.locator(".combat-access-phase").evaluate(row => [...row.children].every(child => {
    const bounds = child.getBoundingClientRect(), parent = row.getBoundingClientRect();
    return bounds.left >= parent.left && bounds.right <= parent.right + 1 && child.scrollWidth <= child.clientWidth + 1;
  }));
  expect(fits).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("objetos-compacto.png") });
  expect(errors).toEqual([]);
});
