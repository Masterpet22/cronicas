import assert from "node:assert/strict";
import { createCharacter, createDefaultSave } from "../src/save.js";
import { BASE_ACTIONS } from "../src/data.js";
import { actionHealthCost, physicalActionAvailable, physicalEmptySkill, physicalSkillActions, skillResourceLabel } from "../src/battle/skill-tables.js";
import { investResonance } from "../src/skills/progression.js";
import { equipTaijutsu, normalizeTaijutsuLoadout, taijutsuAction, unequipTaijutsu } from "../src/skills/taijutsu.js";
import { normalizeSave } from "../src/save.js";

const save = createCharacter(createDefaultSave(), { name: "Akio", affinity: "fuego" });
const original = structuredClone(save);
const elemental = [BASE_ACTIONS[0], { id: "fire_embers" }, null, null, null, BASE_ACTIONS[1]];
const physical = physicalSkillActions(save, elemental);
assert.equal(physical[0], elemental[0]); assert.equal(physical[5], elemental[5]);
assert.equal(physical[1].weaponId, "kunai"); assert.match(physical[1].equipmentName, /Kunai/);
assert.equal(physical[1].cost, 0); assert.equal(physical[1].damage, BASE_ACTIONS[0].damage);
assert.equal(physical[2].weaponId, "shuriken");
assert.equal(physical[2].cost, 0); assert.equal(physical[2].healthCost, 0);
assert.deepEqual(physical.slice(3, 5), [null, null]);
assert.equal(physicalEmptySkill(2).name, "Arma arrojadiza");
assert.match(physicalEmptySkill(3).description, /vida en lugar de chakra/);
assert.deepEqual(save, original, "Cambiar de tabla no modifica la partida ni el equipo");
const disarmed = structuredClone(save); disarmed.equipment.weapon = null;
disarmed.equipment.throwable = null;
assert.equal(physicalSkillActions(disarmed, elemental)[2], null);
disarmed.equipment.throwable = "shuriken"; delete disarmed.inventory.items.shuriken;
assert.equal(physicalSkillActions(disarmed, elemental)[2], null, "Un arma arrojadiza que no posees no se puede usar");
assert.equal(physicalSkillActions(disarmed, elemental)[1], null);
disarmed.equipment.weapon = "sword";
assert.equal(physicalSkillActions(disarmed, elemental)[1], null, "Un arma que no posees no se puede usar");
const scene = { player: { hp: 20, chakra: 0 }, busy: false, finished: false, turnReady: true, cooldowns: {}, actionCost: action => action.cost, scene: { isPaused: () => false } };
assert.ok(physicalActionAvailable(scene, physical[1]), "El arma funciona sin chakra");
const taijutsu = { id: "example", cost: 0, healthCost: 8 };
assert.equal(skillResourceLabel(scene, taijutsu, true), "8 PV");
assert.equal(skillResourceLabel(scene, elemental[0]), "0 CH");
assert.equal(actionHealthCost({ healthCost: -10 }), 0);
scene.player.hp = 8;
assert.equal(physicalActionAvailable(scene, taijutsu), false, "El coste físico no puede matar al usuario");
scene.player.hp = 9; assert.ok(physicalActionAvailable(scene, taijutsu));
scene.cooldowns.example = 1; assert.equal(physicalActionAvailable(scene, taijutsu), false);
let trained = investResonance(save,"physical_0");
assert.equal(equipTaijutsu(trained,0,"physical_1"),trained,"No se equipa un taijutsu bloqueado");
trained = investResonance(investResonance(trained,"physical_1"),"physical_2");
trained = equipTaijutsu(equipTaijutsu(trained,0,"physical_1"),1,"physical_2");
assert.deepEqual(trained.taijutsuLoadout,["physical_1","physical_2"]);
assert.deepEqual(trained.loadout,save.loadout,"Taijutsu no consume ranuras elementales");
assert.deepEqual(physicalSkillActions(trained,elemental).slice(3,5).map(action => action.id),trained.taijutsuLoadout);
assert.deepEqual(normalizeSave(JSON.parse(JSON.stringify(trained))).taijutsuLoadout,trained.taijutsuLoadout,"Los dos huecos persisten al guardar");
const swapped = equipTaijutsu(trained,1,"physical_1");
assert.deepEqual(swapped.taijutsuLoadout,["physical_2","physical_1"],"Mover entre ranuras intercambia y no duplica técnicas");
assert.deepEqual(unequipTaijutsu(swapped,0).taijutsuLoadout,[null,"physical_1"],"Retirar conserva la posición de la otra ranura");
assert.deepEqual(normalizeTaijutsuLoadout(trained,["physical_1","physical_1","physical_2"]),["physical_1",null]);
assert.deepEqual(normalizeTaijutsuLoadout(save,["physical_1","bad"]),[null,null]);
assert.equal(equipTaijutsu(trained,2,"physical_1"),trained);
trained.progression.level=2;
trained = investResonance(trained,"physical_1");
assert.equal(taijutsuAction(trained,"physical_1").damage,24,"El rango del nodo mejora también el golpe equipado");
assert.deepEqual(normalizeSave({ ...trained,taijutsuLoadout:undefined }).taijutsuLoadout,[null,null],"Partidas anteriores reciben dos ranuras vacías");
console.log("Tablas de habilidades: ranuras fijas, arma equipada, reservas físicas y costes de vida verificados.");
