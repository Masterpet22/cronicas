for (let year = 2026; year <= 2030; year++) for (let month = 1; month <= 12; month++) {
  const key = `${year}-${String(month).padStart(2, "0")}`, days = monthLength(key), cells = calendarMonth(key);
  assert.equal(cells.filter(Boolean).length, days);
  cells.forEach((day, index) => { if (day) assert.equal(new Date(day + "T12:00:00Z").getUTCDay(), index % 7); });
  const events = eventsBetween(`${key}-01`, `${key}-${days}`);
  const second = events.find(item => item.id === "second-friday-visit"), last = events.find(item => item.id === "last-friday-visit");
  assert.equal(new Date(second.start + "T12:00:00Z").getUTCDay(), 5);
  assert.ok(Number(second.start.slice(-2)) >= 8 && Number(second.start.slice(-2)) <= 14);
  assert.equal(new Date(last.start + "T12:00:00Z").getUTCDay(), 5);
  assert.ok(Number(last.start.slice(-2)) > days - 7);
  const festival = events.find(item => item.id === "elemental-festival");
  assert.equal(festival.start, `${key}-${String(days - 2).padStart(2, "0")}`);
  assert.equal(festival.end, `${key}-${days}`);
  assert.equal(festival.endDay - festival.startDay, 2);
  for (const [day, element] of [[5, "agua"], [12, "tierra"], [19, "fuego"], [26, "viento"]]) assert.equal(events.find(item => item.id === `element-day-${element}`).start, `${key}-${String(day).padStart(2, "0")}`);
}
