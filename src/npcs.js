export const LOCATION_CAST = {
  headquarters: ["ren"],
  dojo: ["daichi", "mei"],
  archive: ["sayo"],
  shop: ["hana"],
  tower: ["kureha"],
  arena: ["goro"],
  inn: ["yuna"],
  missions: ["riku"],
  event: ["nao"]
};

export function locationDialogue(locationId, type = "intro") {
  return (LOCATION_CAST[locationId] || []).flatMap((id) => {
    const npc = NPCS[id];
    return (npc?.[type] || []).map((text) => [npc.name, text]);
  });
}

export function npcByName(name) {
  return Object.values(NPCS).find((npc) => npc.name === name) || null;
}
