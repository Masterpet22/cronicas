export function characterHairConfig(bodyType, style) {
  const hair = CHARACTER_HAIR[style];
  if (!hair || bodyType !== "female") return hair || null;
  const male = CHARACTER_RIGS.male;
  const female = CHARACTER_RIGS.female;
  const maleHead = male.byId.cabeza;
  const femaleHead = female.byId.cabeza;
  const scale = femaleHead.scaleX || 1;
  return {
    ...hair,
    x: femaleHead.x + (male.joints.neck.x + hair.x - maleHead.x) * scale - female.joints.neck.x,
    y: femaleHead.y + (male.joints.neck.y + hair.y - maleHead.y) * scale - female.joints.neck.y,
    width: hair.width * scale,
    height: hair.height * scale
  };
}
